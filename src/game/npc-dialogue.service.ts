/** 返回符合当前时间段与好感阶段的随机闲聊。 */
export const npcChatDialogue = (code: NpcDialogueCode, affinity: number) => {
  const pool = dialoguePools[code];
  const period = currentPeriod();
  return `${choose(pool.scenes[period])}\n${choose(pool.relations[relationFor(affinity)])}`;
};
