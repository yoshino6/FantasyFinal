export type NpcDialogueCode = 'pear_guide' | 'guild_counter' | 'blacksmith' | 'alchemy_sweetshop';

type Period = 'morning' | 'afternoon' | 'evening';
type Relation = 'stranger' | 'acquaintance' | 'friend' | 'close_friend' | 'confidant';
