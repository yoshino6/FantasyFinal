实施时应一次性替换旧甲类双防倍率、旧六项修正和旧套装效果；不能新旧叠加。普通神器装备上的特殊效果是否适用甲类规则，必须沿用最终确定的装备归属口径，不能通过甲类调整顺带削改神器效果。生命／魔力套装应增加上限，不在每次重算或换装时免费补满；普通回魔与治疗机制另行处理。

