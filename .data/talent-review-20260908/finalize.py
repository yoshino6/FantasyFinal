review=['\n## 11. 100项逐条复核结论\n','本节覆盖全部100项。修订包括数值、适用条件与真实结算边界；未改倍率的条目也列明保留依据。与V1相比，85项有数值或机制修订，15项维持核心参数。第3节与第5节为唯一现行效果，本文没有“仅建议、目录仍旧值”的双重版本。\n']
for num,title,body in parts:
    body=body.split('\n#### ')[0]
    matches=list(re.finditer(r'^\| ([A-Z]\d{2}) ([^|]+)\|[^\n]+',body,re.M))
    assert len(matches)==10,(title,len(matches))
    review += [f'### 11.{num} {title}\n','| 天赋 | 结论 | 复核依据 |','| --- | --- | --- |']
    for m in matches:
        code=m.group(1);name=m.group(2).strip();new_rows[code]=m.group(0)
        changed=m.group(0)!=audit['old'][code] or code.startswith('U')
        review.append(f"| {code} {name} | {'修订' if changed else '保留'} | {audit['notes'][code]} |")
    review.append('')
assert len(new_rows)==100
changes=sum(new_rows[k]!=audit['old'][k] or k.startswith('U') for k in new_rows)
assert changes==85,changes
s+='\n'.join(review)+'\n'
(root/'docs/初始天赋重设计方案V2.md').write_text(s,encoding='utf-8')
(data/'final-audit.json').write_text(json.dumps({'count':100,'changed':changes,'retained':100-changes,'rows':new_rows,'notes':audit['notes']},ensure_ascii=False,indent=2),encoding='utf-8')
print('V2 written; reviewed=100; revised=',changes,'retained=',100-changes)
